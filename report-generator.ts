/**
 * TruthCheck AI - Academic Verification Report Generator
 * 
 * Provides printable dossiers, PDF export triggers, and structured report downloads
 * for B.Tech CSE AI & ML project audits.
 */

import { VerificationResult } from './types';

export function downloadJsonReport(result: VerificationResult) {
  const dataStr = 'data:text/json;charset=utf-8,' + encodeURIComponent(JSON.stringify(result, null, 2));
  const downloadAnchor = document.createElement('a');
  downloadAnchor.setAttribute('href', dataStr);
  downloadAnchor.setAttribute('download', `truthcheck-report-${result.id}.json`);
  document.body.appendChild(downloadAnchor);
  downloadAnchor.click();
  downloadAnchor.remove();
}

export function downloadTextReport(result: VerificationResult, lang: 'en' | 'te' = 'en') {
  const isTe = lang === 'te';
  const divider = '='.repeat(70);
  const subDivider = '-'.repeat(70);

  const content = `${divider}
TRUTHCHECK AI — OFFICIAL NEWS VERIFICATION DOSSIER
B.Tech CSE (AI & ML) Minor Project Deliverable
${divider}

VERIFICATION ID:     ${result.id}
TIMESTAMP:           ${new Date(result.timestamp).toLocaleString()}
INPUT MODE:          ${result.inputMode.toUpperCase()}
LANGUAGE:            ${result.language === 'te' ? 'Telugu (తెలుగు)' : 'English'}

${subDivider}
FINAL VERDICT:       ${result.finalVerdict}
${subDivider}

EXPLANATION:
${result.verdictExplanation}

${result.divergenceNotes ? `DIVERGENCE NOTICE:\n${result.divergenceNotes}\n` : ''}
${subDivider}
1. MACHINE LEARNING MODEL SIGNAL (TF-IDF + Stylometry)
${subDivider}
- Predicted Label:           ${result.mlResult.predictedLabel}
- Stylistic Confidence:      ${result.mlResult.confidenceScore}%
- Sensationalism Score:      ${result.mlResult.stylometricSignals.sensationalismScore} / 100
- Journalistic Attribution:  ${result.mlResult.stylometricSignals.journalisticAttributionScore} / 100
- Screaming Uppercase Ratio: ${(result.mlResult.stylometricSignals.uppercaseRatio * 100).toFixed(1)}%

Linguistic Cues Detected:
${result.mlResult.stylometricSignals.linguisticRedFlags.map(f => `  [!] ${f}`).join('\n') || '  None'}

Journalistic Markers Detected:
${result.mlResult.stylometricSignals.journalisticMarkers.map(m => `  [+] ${m}`).join('\n') || '  None'}

${subDivider}
2. REAL-TIME INTERNET EVIDENCE ASSESSMENT
${subDivider}
- Status:            ${result.evidenceResult.status}
- Evidence Strength: ${result.evidenceResult.evidenceStrength}
- Consensus Summary: ${result.evidenceResult.consensusSummary}

Identified Claims:
${result.evidenceResult.mainClaimsIdentified.map((c, i) => `  ${i + 1}. ${c}`).join('\n')}

Supporting Evidence:
${result.evidenceResult.supportingEvidence.map(e => `  - ${e.claim}: ${e.explanation}`).join('\n') || '  None found'}

Contradicting Evidence & Debunks:
${result.evidenceResult.contradictingEvidence.map(e => `  - ${e.claim}: ${e.explanation}`).join('\n') || '  None found'}

${subDivider}
3. VERIFIED CITATIONS & SOURCES (${result.evidenceResult.allSources.length} links)
${subDivider}
${result.evidenceResult.allSources.map((s, i) => `  ${i + 1}. ${s.title}\n     URL: ${s.url}\n     Publisher: ${s.publisher || 'N/A'} [${s.credibilityTier || 'Web Source'}]`).join('\n\n') || '  No external URLs retrieved'}

${subDivider}
4. PROJECT LIMITATIONS & ACADEMIC DISCLAIMER
${subDivider}
- ${result.limitations.join('\n- ')}

DISCLAIMER:
The ML confidence score reflects linguistic and lexical similarity to training datasets (ISOT/LIAR), not an infallible guarantee of factual truth. Factual truth is determined by real-time evidence and official records.

${divider}
Generated by TruthCheck AI Engine — B.Tech CSE AI & ML Project
${divider}
`;

  const blob = new Blob([content], { type: 'text/plain;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `truthcheck-dossier-${result.id}.txt`;
  document.body.appendChild(a);
  a.click();
  a.remove();
  URL.revokeObjectURL(url);
}

